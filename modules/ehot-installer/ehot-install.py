#!/usr/bin/env python3
"""
EHOT OS Safe Guided & Automated Installer (`ehot-install`).
Designed for bare Lenovo laptops booted from Kingston DataTraveler 64 GB Live USB.

Safety invariants:
  1. Never guesses /dev/sda. Strictly uses `disk_detect.py` to exclude USB,
     removable, read-only, and live boot media.
  2. Shows target disk model, serial, size, and existing partitions, requiring
     explicit owner confirmation before wiping.
  3. Never hardcodes passwords in ISO or scripts: prompts owner interactively
     for user `Regzen` password.
  4. Supports both UEFI (GPT + FAT32 ESP) and Legacy BIOS (GPT + bios_grub)
     cleanly without requiring internet during base deployment.
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List, Optional

INSTALLER_DIR = Path(__file__).resolve().parent
if str(INSTALLER_DIR) not in sys.path:
    sys.path.insert(0, str(INSTALLER_DIR))

from disk_detect import DiskCandidate, scan_system_disks, select_target_disk  # noqa: E402

TARGET_USERNAME = "Regzen"
DEFAULT_HOSTNAME = "ehot-lenovo"
DEFAULT_TIMEZONE = "Europe/Moscow"
DEFAULT_LOCALE = "ru_RU.UTF-8"
SQUASHFS_CANDIDATES = (
    Path("/cdrom/casper/filesystem.squashfs"),
    Path("/run/live/medium/casper/filesystem.squashfs"),
    Path("/lib/live/mount/medium/casper/filesystem.squashfs"),
)


def run_cmd(cmd: List[str], check: bool = True, input_text: Optional[str] = None) -> subprocess.CompletedProcess:
    print(f"+ {' '.join(cmd)}")
    return subprocess.run(cmd, text=True, input=input_text, check=check)


def is_uefi_boot() -> bool:
    return Path("/sys/firmware/efi").is_dir()


def find_squashfs() -> Path:
    for p in SQUASHFS_CANDIDATES:
        if p.exists():
            return p
    raise FileNotFoundError("Не найден образ /cdrom/casper/filesystem.squashfs (запустите из Live-среды EHOT OS).")


def partition_disk_gpt(disk_path: str) -> tuple[str, str]:
    """
    Wipes old partition table safely and creates clean GPT layout:
      p1: 1 MiB EF02 (bios_grub for Legacy BIOS compatibility)
      p2: 512 MiB EF00 (EFI System Partition, FAT32)
      p3: Remaining space 8300 (Linux root ext4)
    Returns (efi_part_path, root_part_path).
    """
    run_cmd(["wipefs", "--all", "--force", disk_path])
    run_cmd(["sgdisk", "--zap-all", disk_path])
    run_cmd(["sgdisk", "--clear", disk_path])
    run_cmd(["sgdisk", "-n", "1:2048:+1M", "-t", "1:EF02", "-c", "1:BIOS_GRUB", disk_path])
    run_cmd(["sgdisk", "-n", "2:0:+512M", "-t", "2:EF00", "-c", "2:EFI_SYS", disk_path])
    run_cmd(["sgdisk", "-n", "3:0:0", "-t", "3:8300", "-c", "3:EHOT_ROOT", disk_path])
    run_cmd(["partprobe", disk_path], check=False)
    run_cmd(["udevadm", "settle"], check=False)

    sep = "p" if re.search(r"\d$", disk_path) else ""
    efi_part = f"{disk_path}{sep}2"
    root_part = f"{disk_path}{sep}3"

    run_cmd(["mkfs.vfat", "-F", "32", "-n", "EHOTEFI", efi_part])
    run_cmd(["mkfs.ext4", "-F", "-L", "EHOT_ROOT", root_part])
    return efi_part, root_part


def get_uuid(part_path: str) -> str:
    res = subprocess.run(["blkid", "-s", "UUID", "-o", "value", part_path], capture_output=True, text=True, check=True)
    return res.stdout.strip()


def prompt_owner_password() -> str:
    while True:
        p1 = getpass.getpass(f"Введите новый пароль для администратора '{TARGET_USERNAME}' (мин. 4 символа): ")
        p2 = getpass.getpass("Повторите пароль: ")
        if p1 != p2:
            print("Пароли не совпадают. Повторите попытку.")
            continue
        if len(p1) < 4:
            print("Пароль слишком короткий (минимум 4 символа).")
            continue
        return p1


def deploy_system(
    target_disk: DiskCandidate,
    regzen_password: str,
    hostname: str,
    timezone: str,
) -> None:
    squashfs_path = find_squashfs()
    efi_part, root_part = partition_disk_gpt(target_disk.path)

    root_uuid = get_uuid(root_part)
    efi_uuid = get_uuid(efi_part)

    mount_dir = Path(tempfile.mkdtemp(prefix="ehot-target-"))
    mounted_virtual = False
    try:
        run_cmd(["mount", root_part, str(mount_dir)])
        (mount_dir / "boot" / "efi").mkdir(parents=True, exist_ok=True)
        run_cmd(["mount", efi_part, str(mount_dir / "boot" / "efi")])

        print("[ehot-install] Распаковка системы на целевой диск (может занять несколько минут на HDD)...")
        run_cmd(["unsquashfs", "-f", "-d", str(mount_dir), str(squashfs_path)])

        # Write clean /etc/fstab with UUIDs, noatime for HDD responsiveness, and /swapfile entry
        fstab_content = (
            "# /etc/fstab: generated by EHOT OS Installer\n"
            f"UUID={root_uuid} / ext4 noatime,errors=remount-ro 0 1\n"
            f"UUID={efi_uuid} /boot/efi vfat umask=0077 0 2\n"
            "/swapfile none swap sw,pri=10 0 0\n"
        )
        (mount_dir / "etc" / "fstab").write_text(fstab_content, encoding="utf-8")

        # Hostname & hosts
        (mount_dir / "etc" / "hostname").write_text(f"{hostname}\n", encoding="utf-8")
        hosts_text = (
            "127.0.0.1\tlocalhost\n"
            f"127.0.1.1\t{hostname}\n"
            "::1\tlocalhost ip6-localhost ip6-loopback\n"
        )
        (mount_dir / "etc" / "hosts").write_text(hosts_text, encoding="utf-8")

        # Create 4 GB /swapfile directly on target HDD (priority 10, secondary to ZRAM)
        swapfile = mount_dir / "swapfile"
        if not swapfile.exists():
            print("[ehot-install] Создание /swapfile (4 ГБ)...")
            res = subprocess.run(["fallocate", "-l", "4G", str(swapfile)], check=False)
            if res.returncode != 0:
                run_cmd(["dd", "if=/dev/zero", f"of={swapfile}", "bs=1M", "count=4096"])
            os.chmod(swapfile, 0o600)
            run_cmd(["mkswap", str(swapfile)])

        # Bind mount virtual filesystems for chroot configuration
        for vfs in ("dev", "dev/pts", "proc", "sys", "run"):
            src = f"/{vfs}"
            dst = mount_dir / vfs
            dst.mkdir(parents=True, exist_ok=True)
            run_cmd(["mount", "--bind", src, str(dst)])
        mounted_virtual = True
        if Path("/sys/firmware/efi/efivars").is_dir():
            efivars_dst = mount_dir / "sys" / "firmware" / "efi" / "efivars"
            efivars_dst.mkdir(parents=True, exist_ok=True)
            run_cmd(["mount", "--bind", "/sys/firmware/efi/efivars", str(efivars_dst)], check=False)

        # Configure user Regzen, remove live-only bits, regenerate machine-id, install GRUB
        chroot_script = f"""
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

rm -f /etc/machine-id
systemd-machine-id-setup

ln -sf /usr/share/zoneinfo/{timezone} /etc/localtime
echo "{timezone}" > /etc/timezone
locale-gen en_US.UTF-8 ru_RU.UTF-8 || true
update-locale LANG={DEFAULT_LOCALE} || true

# Remove live user 'mint' if present and create owner account '{TARGET_USERNAME}'
if id -u mint >/dev/null 2>&1; then
  userdel -r -f mint || true
fi
if ! id -u "{TARGET_USERNAME}" >/dev/null 2>&1; then
  useradd -m -s /bin/bash -G sudo,adm,cdrom,dip,plugdev,lpadmin,sambashare,video,audio,render,input "{TARGET_USERNAME}"
fi
# Apply skeleton configs if home was created earlier
cp -rn /etc/skel/. "/home/{TARGET_USERNAME}/" || true
chown -R "{TARGET_USERNAME}:{TARGET_USERNAME}" "/home/{TARGET_USERNAME}"

# Remove live-only desktop installer shortcut and live packages
rm -f "/home/{TARGET_USERNAME}/Desktop/ehot-install.desktop" /etc/skel/Desktop/ehot-install.desktop
apt-get purge -y casper lupin-casper ubiquity ubiquity-frontend-gtk ubiquity-slideshow-mint 2>/dev/null || true

# Ensure safe graphics GRUB fallback entry exists and regenerate initramfs
mkdir -p /etc/default/grub.d
cat > /etc/default/grub.d/90-ehot-os.cfg <<'GRUBCFG'
GRUB_DISTRIBUTOR="EHOT OS"
GRUB_TIMEOUT=3
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash"
GRUBCFG

if [ -d /sys/firmware/efi ]; then
  grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id="EHOT_OS" --recheck || \
  grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id="EHOT_OS" --no-nvram --removable
else
  grub-install --target=i386-pc --recheck "{target_disk.path}"
fi

update-initramfs -u -k all || true
update-grub

# Enable first-boot hardware & user setup wizard
systemctl enable ehot-firstboot.service || true
"""
        run_cmd(["chroot", str(mount_dir), "/bin/bash", "-c", chroot_script])

        # Set owner password safely via chpasswd stdin (never exposed on CLI args)
        run_cmd(
            ["chroot", str(mount_dir), "chpasswd"],
            input_text=f"{TARGET_USERNAME}:{regzen_password}\n",
        )
        print(f"\n[ehot-install] УСТАНОВКА EHOT OS УСПЕШНО ЗАВЕРШЕНА на {target_disk.path}!")
        print("Извлеките флешку Kingston DataTraveler после выключения/перезагрузки.")
    finally:
        if mounted_virtual:
            for vfs in ("sys/firmware/efi/efivars", "run", "sys", "proc", "dev/pts", "dev"):
                run_cmd(["umount", "-lf", str(mount_dir / vfs)], check=False)
        run_cmd(["umount", "-lf", str(mount_dir / "boot" / "efi")], check=False)
        run_cmd(["umount", "-lf", str(mount_dir)], check=False)
        shutil.rmtree(mount_dir, ignore_errors=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="EHOT OS Safe Installer")
    parser.add_argument("--target", help="Explicit target internal disk path (e.g. /dev/sdb)")
    parser.add_argument("--hostname", default=DEFAULT_HOSTNAME)
    parser.add_argument("--timezone", default=DEFAULT_TIMEZONE)
    parser.add_argument("--dry-run", action="store_true", help="Inspect disks without modifying anything")
    args = parser.parse_args()

    if os.geteuid() != 0 and not args.dry_run:
        print("Ошибка: запустите установщик от имени root (sudo ehot-install).", file=sys.stderr)
        return 1

    print("=== Установщик EHOT OS (на базе Linux Mint 22.3 XFCE) ===")
    print(f"Режим загрузки: {'UEFI' if is_uefi_boot() else 'Legacy BIOS'}")
    print()

    candidates = scan_system_disks()
    print("Обнаруженные накопители:")
    for c in candidates:
        status = "ДОСТУПЕН ДЛЯ УСТАНОВКИ" if c.eligible else f"ЗАБЛОКИРОВАН ({'; '.join(c.rejection_reasons)})"
        print(f"  * {c.summary_line()} -> {status}")
    print()

    try:
        chosen, warnings = select_target_disk(candidates, preferred_path=args.target)
    except ValueError as exc:
        print(f"ОШИБКА БЕЗОПАСНОСТИ: {exc}", file=sys.stderr)
        return 2

    for w in warnings:
        print(f"ВНИМАНИЕ: {w}")

    if chosen is None:
        print("Установка невозможна: безопасный внутренний накопитель не найден.", file=sys.stderr)
        return 2

    print()
    print("ВЫБРАННЫЙ ЦЕЛЕВОЙ ДИСК ДЛЯ УСТАНОВКИ:")
    print(f"  {chosen.summary_line()}")

    if args.dry_run:
        print("\n[DRY-RUN] Проверка завершена. Диск не изменялся.")
        return 0

    print("\nВНИМАНИЕ! ВСЕ ДАННЫЕ И СТАРЫЕ РАЗДЕЛЫ НА ЭТОМ ДИСКЕ БУДУТ ПОЛНОСТЬЮ УНИЧТОЖЕНЫ.")
    confirm = input(f"Для подтверждения очистки {chosen.path} введите YES: ").strip()
    if confirm != "YES":
        print("Установка отменена пользователем. Данные не изменены.")
        return 0

    regzen_pw = prompt_owner_password()
    deploy_system(chosen, regzen_pw, hostname=args.hostname, timezone=args.timezone)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
